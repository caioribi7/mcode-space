const { contextBridge, ipcRenderer } = require('electron');
const invoke = (channel, ...args) => ipcRenderer.invoke(channel, ...args);
contextBridge.exposeInMainWorld('space', {
  updateState: () => invoke('updates:state'),
  updateCheck: () => invoke('updates:check'),
  updateDownload: () => invoke('updates:download'),
  updateInstall: () => invoke('updates:install'),
  onUpdate: callback => {const listener=(_event,value)=>callback(value);ipcRenderer.on('updates:state',listener);return ()=>ipcRenderer.removeListener('updates:state',listener);},
  todosList: () => invoke('todos:list'),
  todosSave: value => invoke('todos:save',value),
  todosRemove: (id,stamp) => invoke('todos:remove',id,stamp),
  financeStatus: () => invoke('finance:status'),
  accountState: () => invoke('account:state'),
  accountConfigure: value => invoke('account:configure',value),
  accountLogin: value => invoke('account:login',value),
  accountSignup: value => invoke('account:signup',value),
  accountVerify: value => invoke('account:verify',value),
  accountOAuth: provider => invoke('account:oauth',provider),
  accountCancel: () => invoke('account:cancel'),
  accountLogout: () => invoke('account:logout'),
  accountProfile: value => invoke('account:profile',value),
  accountAvatar: () => invoke('account:avatar'),
  financeRead: () => invoke('finance:read'),
  financeAdd: (kind,value) => invoke('finance:add',kind,value),
  financeSettle: (index,expected) => invoke('finance:settle',index,expected),
  contractExport: value => invoke('contracts:export',value),
  agentUsage: () => invoke('agents:usage'),
  initial: () => invoke('workspace:initial'),
  openFolder: () => invoke('workspace:open'),
  openChildFolder: (candidate, root) => invoke('workspace:open-child', candidate, root),
  selectWorkspace: root => invoke('workspace:select', root),
  closeWorkspace: (root, dirty) => invoke('workspace:close', root, dirty),
  saveWorkspace: settings => invoke('workspace:save', settings),
  setDirty: value => invoke('workspace:dirty', value),
  list: (candidate, root) => invoke('files:list', candidate, root),
  read: (candidate, root) => invoke('files:read', candidate, root),
  save: (value, root) => invoke('files:save', value, root),
  move: (candidate, directory, root) => invoke('files:move', candidate, directory, root),
  readImage: (candidate, root) => invoke('files:image', candidate, root),
  openLink: url => invoke('markdown:open-link', url),
  confirmDiscard: name => invoke('files:confirm-discard', name),
  createTerminal: options => invoke('terminal:create', options),
  write: (id, data) => invoke('terminal:write', id, data),
  resize: (id, cols, rows) => invoke('terminal:resize', id, cols, rows),
  closeTerminal: id => invoke('terminal:close', id),
  gitStatus: root => invoke('git:status', root),
  onData: callback => { const listener = (_event, value) => callback(value); ipcRenderer.on('terminal:data', listener); return () => ipcRenderer.removeListener('terminal:data', listener); },
  onExit: callback => { const listener = (_event, value) => callback(value); ipcRenderer.on('terminal:exit', listener); return () => ipcRenderer.removeListener('terminal:exit', listener); },
});

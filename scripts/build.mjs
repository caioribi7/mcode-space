import { build } from 'esbuild';
import { cp, mkdir, lstat, rm } from 'node:fs/promises';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url)).replace(/[\\/]$/,'');
const output=join(root,'dist');
if(dirname(output)!==root||basename(output)!=='dist')throw new Error('Diretório de build inválido.');
const existing=await lstat(output).catch(error=>{if(error.code!=='ENOENT')throw error;return null;});
if(existing?.isSymbolicLink())throw new Error('O build não remove diretórios vinculados.');
if(existing&&!existing.isDirectory())throw new Error('dist/ deve ser um diretório de build.');
await rm(output,{recursive:true,force:true});
await mkdir(output, { recursive: true });
await build({ absWorkingDir:root, entryPoints: ['src/app.js'], bundle: true, outfile: join(output,'app.js'), format: 'iife', minify:true, sourcemap: false, legalComments:'eof', loader: { '.ttf': 'file' }, target: 'chrome140' });
await cp(join(root,'src/index.html'), join(output,'index.html'));
await cp(join(root,'assets'), join(output,'assets'), { recursive: true, filter:source=>!source.endsWith('.ttf')&&basename(source)!=='README.md' });
console.log('MCode Space preparado em dist/.');
